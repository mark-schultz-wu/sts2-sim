//! The affliction table against the dump it came from.
//!
//! The card-side twin of the enchantment table, and the interesting difference
//! is what codegen does *not* do to it. Enchantments come out narrowed, because
//! the base `CanEnchant` refuses three card types outright and the probe answers
//! for them anyway. Afflictions have no such blanket rule, so the probe is the
//! answer. The only thing dropped between the dump and the table is
//! `CardType::None`, which the cards domain does not generate.

use super::super::afflictions::*;
use super::super::cards::CardType;
use super::super::{AFFLICTIONS, VERSION};
use super::{build, rows, wire};
use std::collections::{BTreeMap, BTreeSet};

fn affliction(id: &str) -> Affliction {
    *Affliction::ALL
        .iter()
        .find(|a| wire(a) == id)
        .unwrap_or_else(|| panic!("{id} is in the dump but not generated"))
}

/// The card type the probe answers for and the cards domain does not generate.
const UNMODELLED: &str = "None";

/// The anchor: a dump from another build has another hash.
#[test]
fn the_dump_came_from_this_version() {
    assert_eq!(
        build(AFFLICTIONS),
        VERSION,
        "afflictions.txt was dumped from a different build than this module claims"
    );
}

#[test]
fn the_generated_table_matches_the_dump() {
    let mut checked = 0;

    for row in rows(AFFLICTIONS, "affliction") {
        let id = row[1];
        let d = affliction(id).data();

        for (column, flag) in [
            (2, AfflictionFlag::Stackable),
            (3, AfflictionFlag::AfflictsUnplayableCards),
            (4, AfflictionFlag::ExtraCardText),
        ] {
            let set = if d.flags.contains(flag) { "1" } else { "0" };
            assert_eq!(set, row[column], "{id}: {flag:?}");
        }

        checked += 1;
    }

    assert_eq!(checked, 10, "the build has 10 afflictions");
    assert_eq!(Affliction::ALL.len(), 10);
}

/// `afflicts` is the probe, minus the one card type that cannot be spelled.
///
/// Not an intersection with a second rule the way `enchants` is. The base
/// `CanAfflict` refuses no card type at all, so whatever `CanAfflictCardType`
/// answered is what an affliction can go on. Rebuilt here from the dump rather
/// than trusted, because dropping `None` is the one step codegen takes.
#[test]
fn afflicts_is_the_probe_without_the_type_that_cannot_be_spelled() {
    let mut probed: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for row in rows(AFFLICTIONS, "afflicts") {
        probed.entry(row[1]).or_default().push(row[2]);
    }

    for a in Affliction::ALL {
        let id = wire(&a);
        let answers = probed
            .get(id.as_str())
            .unwrap_or_else(|| panic!("{id} was never probed"));

        let want: Vec<&str> = answers
            .iter()
            .copied()
            .filter(|t| *t != UNMODELLED)
            .collect();
        let got: Vec<String> = a.data().afflicts.iter().map(|t| wire(&t)).collect();

        assert_eq!(got, want, "{id}: afflictable types");
        assert!(!got.is_empty(), "{id} can be stuck to nothing");
    }

    // `CardType::None` is not generated by the cards domain, so there is no way
    // to spell an affliction claiming it.
    assert!(serde_json::from_str::<CardType>("\"None\"").is_err());
}

/// Every affliction but one takes any card, and `None` is the only drop.
///
/// This is the claim that makes the test above a check rather than a tautology.
/// Nine of the ten accept all seven types the probe offers. The only reason
/// their generated set has six is the one this table cannot name.
#[test]
fn only_tainted_restricts_its_card_types() {
    let restricted: Vec<(String, Vec<String>)> = Affliction::ALL
        .iter()
        .filter(|a| a.data().afflicts.iter().count() < 6)
        .map(|a| {
            (
                wire(a),
                a.data().afflicts.iter().map(|t| wire(&t)).collect(),
            )
        })
        .collect();

    assert_eq!(
        restricted,
        [("TAINTED".to_string(), vec!["Skill".to_string()])],
        "the afflictions that restrict their card types have changed"
    );

    // The other nine accept everything the probe offered, `None` included.
    let unrestricted: BTreeSet<&str> = rows(AFFLICTIONS, "afflicts")
        .filter(|r| r[2] == UNMODELLED)
        .map(|r| r[1])
        .collect();
    assert_eq!(unrestricted.len(), Affliction::ALL.len() - 1);
}

/// Nothing has a rule beyond the card's type, and the dropped column says so.
///
/// Five enchantments override `CanEnchant` and refuse a card their type allows.
/// No affliction overrides `CanAfflict`, so there is no such flag here. Codegen
/// refuses to generate if one ever appears, and this says the same from the
/// dump's side. The column is still written, so the claim stays checkable.
#[test]
fn no_affliction_refuses_a_card_its_type_allows() {
    assert!(
        rows(AFFLICTIONS, "affliction").all(|r| r[5] == "0"),
        "an affliction now refuses cards its type allows, and the dropped column would hide it"
    );
}

/// Two afflictions stack, and only a mock refuses unplayable cards.
///
/// `AfflictsUnplayableCards` is the odd one: every affliction the game ships
/// has it, and the single model without it is a test fixture. Worth pinning
/// rather than reading the count as a rule. The flag exists because the base
/// `CanAfflict` consults it, not because any real affliction says no.
#[test]
fn the_flags_are_as_rare_as_they_look() {
    let with = |flag: AfflictionFlag| -> Vec<String> {
        Affliction::ALL
            .iter()
            .filter(|a| a.data().flags.contains(flag))
            .map(wire)
            .collect()
    };

    assert_eq!(
        with(AfflictionFlag::Stackable),
        ["GALVANIZED", "MOCK_SELF_DAMAGE_AFFLICTION", "TAINTED"]
    );
    assert_eq!(
        Affliction::ALL
            .iter()
            .filter(|a| !a
                .data()
                .flags
                .contains(AfflictionFlag::AfflictsUnplayableCards))
            .map(wire)
            .collect::<Vec<_>>(),
        ["MOCK_NO_UNPLAYABLE_AFFLICTION"]
    );
    assert_eq!(
        with(AfflictionFlag::ExtraCardText),
        ["BOUND", "GALVANIZED", "RINGING", "TAINTED"]
    );
}

/// The wire form round-trips, and it is the only spelling of an id.
#[test]
fn an_affliction_round_trips_through_its_wire_form() {
    let dumped: Vec<&str> = rows(AFFLICTIONS, "affliction").map(|r| r[1]).collect();

    for (a, id) in Affliction::ALL.iter().zip(&dumped) {
        let json = serde_json::to_string(a).unwrap();
        assert_eq!(json, format!("\"{id}\""), "the rename is not the dump's id");
        assert_eq!(&serde_json::from_str::<Affliction>(&json).unwrap(), a);
    }

    assert!(serde_json::from_str::<Affliction>("\"NOT_AN_AFFLICTION\"").is_err());
}
