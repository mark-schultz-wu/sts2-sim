//! The enchantment table against the dump it came from.
//!
//! The particular thing here is that `enchants` is not what the dump says. The
//! dump records what `CanEnchantCardType` answered about every card type. The
//! table records what an enchantment can actually be put on, which is that
//! intersected with the three types `CanEnchant` does not refuse outright. The
//! tests below check both halves, because the intersection is the one step
//! codegen takes that the dump cannot show.

use super::super::cards::{CardType, CardTypeSet};
use super::super::enchantments::*;
use super::super::{ENCHANTMENTS, VERSION};
use super::{build, rows, wire};
use std::collections::{BTreeMap, BTreeSet};

fn enchantment(id: &str) -> Enchantment {
    *Enchantment::ALL
        .iter()
        .find(|e| wire(e) == id)
        .unwrap_or_else(|| panic!("{id} is in the dump but not generated"))
}

/// The three card types `EnchantmentModel.CanEnchant` does not refuse.
const ENCHANTABLE: [&str; 3] = ["Attack", "Skill", "Power"];

/// The anchor: a dump from another build has another hash.
#[test]
fn the_dump_came_from_this_version() {
    assert_eq!(
        build(ENCHANTMENTS),
        VERSION,
        "enchantments.txt was dumped from a different build than this module claims"
    );
}

#[test]
fn the_generated_table_matches_the_dump() {
    let mut checked = 0;

    for row in rows(ENCHANTMENTS, "enchantment") {
        let id = row[1];
        let d = enchantment(id).data();

        for (column, flag) in [
            (2, EnchantmentFlag::ExtraCardText),
            (3, EnchantmentFlag::ShowsAmount),
            (4, EnchantmentFlag::StartsAtBottomOfDrawPile),
            (6, EnchantmentFlag::RefusesSomeCards),
        ] {
            let set = if d.flags.contains(flag) { "1" } else { "0" };
            assert_eq!(set, row[column], "{id}: {flag:?}");
        }

        checked += 1;
    }

    assert_eq!(checked, 24, "the build has 24 enchantments");
    assert_eq!(Enchantment::ALL.len(), 24);
}

/// `enchants` is the probe intersected with what `CanEnchant` allows.
///
/// This is the one place codegen does something the dump does not show, so it is
/// rebuilt here from the dump rather than trusted. The answer for a type outside
/// the three is dropped, and the answer for a type inside them is kept exactly.
#[test]
fn enchants_is_the_probe_narrowed_to_the_reachable_types() {
    let mut probed: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    for row in rows(ENCHANTMENTS, "enchants") {
        probed.entry(row[1]).or_default().insert(row[2]);
    }

    for e in Enchantment::ALL {
        let id = wire(&e);
        let answers = probed
            .get(id.as_str())
            .unwrap_or_else(|| panic!("{id} was never probed"));

        let want: Vec<String> = ENCHANTABLE
            .iter()
            .filter(|t| answers.contains(*t))
            .map(|t| t.to_string())
            .collect();
        let got: Vec<String> = e.data().enchants.iter().map(|t| wire(&t)).collect();

        assert_eq!(got, want, "{id}: enchantable types");
        assert!(!got.is_empty(), "{id} can be put on nothing");
    }
}

/// The probe says yes to more than an enchantment can reach.
///
/// Seventeen of the twenty-four accept every card type the probe offers,
/// including `Curse`, `Status`, `Quest` and the game's `CardType.None`. The base
/// `CanEnchantCardType` returns true for anything, and the real filter is in
/// `CanEnchant`. If that ever stops being so, the intersection above is
/// narrowing something real, so it is worth saying that today it is not.
#[test]
fn the_probe_answers_for_types_no_enchantment_can_reach() {
    let unreachable: BTreeSet<&str> = rows(ENCHANTMENTS, "enchants")
        .map(|r| r[2])
        .filter(|t| !ENCHANTABLE.contains(t))
        .collect();

    assert_eq!(
        unreachable.into_iter().collect::<Vec<_>>(),
        ["Curse", "None", "Quest", "Status"],
        "the types the probe accepts but nothing can reach have changed"
    );

    // `CardType::None` is not generated by the cards domain, so an enchantment
    // claiming it could not be spelled here even if it were reachable.
    assert!(serde_json::from_str::<CardType>("\"None\"").is_err());
}

/// Exactly the enchantments that restrict their card types.
#[test]
fn only_seven_enchantments_restrict_their_card_types() {
    let restricted: Vec<(String, Vec<String>)> = Enchantment::ALL
        .iter()
        .filter(|e| e.data().enchants.iter().count() < ENCHANTABLE.len())
        .map(|e| {
            (
                wire(e),
                e.data().enchants.iter().map(|t| wire(&t)).collect(),
            )
        })
        .collect();

    assert_eq!(
        restricted,
        [
            ("CORRUPTED".to_string(), vec!["Attack".to_string()]),
            ("IMBUED".to_string(), vec!["Skill".to_string()]),
            ("INSTINCT".to_string(), vec!["Attack".to_string()]),
            ("MOMENTUM".to_string(), vec!["Attack".to_string()]),
            (
                "ROYALLY_APPROVED".to_string(),
                vec!["Attack".to_string(), "Skill".to_string()]
            ),
            ("SHARP".to_string(), vec!["Attack".to_string()]),
            ("VIGOROUS".to_string(), vec!["Attack".to_string()]),
        ],
        "the enchantments that restrict their card types have changed"
    );

    // The other seventeen take all three.
    let unrestricted = Enchantment::ALL.len() - restricted.len();
    assert_eq!(unrestricted, 17);
}

/// `IsStackable` is not a column, and nothing has it.
///
/// It is dropped because all twenty-four take the `false` default, so a column
/// says the same thing twenty-four times. Codegen refuses to generate if one
/// ever stops taking the default, and this says the same from the dump's side.
/// The column is still written, so the claim stays checkable.
#[test]
fn no_enchantment_stacks() {
    assert!(
        rows(ENCHANTMENTS, "enchantment").all(|r| r[5] == "0"),
        "an enchantment is now stackable, and the dropped column would hide it"
    );
}

/// One enchantment starts its card at the bottom of the draw pile.
#[test]
fn the_flags_are_as_rare_as_they_look() {
    let count = |flag: EnchantmentFlag| {
        Enchantment::ALL
            .iter()
            .filter(|e| e.data().flags.contains(flag))
            .count()
    };

    assert_eq!(count(EnchantmentFlag::ExtraCardText), 8);
    assert_eq!(count(EnchantmentFlag::ShowsAmount), 6);
    assert_eq!(count(EnchantmentFlag::StartsAtBottomOfDrawPile), 1);
    assert_eq!(count(EnchantmentFlag::RefusesSomeCards), 5);
}

/// The wire form round-trips, and it is the only spelling of an id.
#[test]
fn an_enchantment_round_trips_through_its_wire_form() {
    let dumped: Vec<&str> = rows(ENCHANTMENTS, "enchantment").map(|r| r[1]).collect();

    for (e, id) in Enchantment::ALL.iter().zip(&dumped) {
        let json = serde_json::to_string(e).unwrap();
        assert_eq!(json, format!("\"{id}\""), "the rename is not the dump's id");
        assert_eq!(&serde_json::from_str::<Enchantment>(&json).unwrap(), e);
    }

    assert!(serde_json::from_str::<Enchantment>("\"NOT_AN_ENCHANTMENT\"").is_err());
}

/// `CardTypeSet` spans every card type, not just the reachable three.
///
/// The set lives in the cards domain beside `CardType`, and is deliberately not
/// narrowed to this domain's use. An enchantment goes on three of the six types,
/// and a set holding only those three is wrong for the next caller. What is
/// narrow is the *value* stored here, not the type.
#[test]
fn the_card_type_set_is_not_narrowed_to_enchantments() {
    let all = CardTypeSet::new(&[
        CardType::Attack,
        CardType::Skill,
        CardType::Power,
        CardType::Status,
        CardType::Curse,
        CardType::Quest,
    ]);
    assert_eq!(all.iter().count(), 6, "the set holds every card type");
    assert!(all.contains(CardType::Curse));

    // Bits are the game's own discriminants, so bit 0 stays unused: `CardType`
    // starts at 1 because its zero is the dropped `None`.
    assert_eq!(CardType::Attack as u8, 1);
    assert!(CardTypeSet::new(&[]).is_empty());
    assert!(!all.is_empty());

    // Every enchantment's value is a subset of the reachable three, which is
    // the domain's rule and not the type's.
    for e in Enchantment::ALL {
        assert!(e.data().enchants.iter().count() <= ENCHANTABLE.len());
    }
}
