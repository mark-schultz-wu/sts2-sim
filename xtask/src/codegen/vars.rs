//! The numbers every build's models print, as consts each build's enum
//! implements.
//!
//! A card's numbers are its build's `var` rows, which `cards` generates.
//! Relics, powers, potions and enchantments dump theirs the same way: the
//! numbers each one's `CanonicalVars` hold. A shared port reads them here, as
//! `V::Relic::SEAL_OF_GOLD_GOLD`, which is 5 in one build and 3 in the next. A const is an immediate, so a port pays nothing for reading one.
//!
//! A trait every build implements can only hold the numbers every build has.
//! A port that names one a build lacks does not compile for it, which is what
//! flags a number that moved to another name. A number that is a string, as
//! `ApplierName` is, is no number and is left out.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use super::DumpError;
use crate::error;

/// One kind of model, by the trait its numbers go on.
struct Kind {
    /// The trait, in `sts2_content::vars`.
    trait_name: &'static str,
    /// The dump its `var` rows are in, under a build's `dumps/`.
    dump: &'static str,
    /// The enum each build generates, after the build's module.
    path: &'static str,
}

const KINDS: &[Kind] = &[
    Kind {
        trait_name: "EnchantmentVars",
        dump: "enchantments.txt",
        path: "enchantments::Enchantment",
    },
    Kind {
        trait_name: "PotionVars",
        dump: "potions.txt",
        path: "potions::Potion",
    },
    Kind {
        trait_name: "PowerVars",
        dump: "powers.txt",
        path: "powers::Power",
    },
    Kind {
        trait_name: "RelicVars",
        dump: "relics.txt",
        path: "relics::Relic",
    },
];

/// One build's numbers of one kind, by model and var name, as the dump
/// prints each.
type Numbers = BTreeMap<(String, String), String>;

/// The `var <model> <name> <base> <calculated> <class>` rows of one dump.
fn numbers(dump: &str) -> Numbers {
    dump.lines()
        .filter_map(|line| {
            let words: Vec<&str> = line.split_whitespace().collect();
            match words.as_slice() {
                ["var", model, name, base, _, class] if !class.starts_with("StringVar") => {
                    Some(((model.to_string(), name.to_string()), base.to_string()))
                }
                _ => None,
            }
        })
        .collect()
}

/// A number as a const's value: an `i32` when every build's is whole, and a
/// [`sts2_core::Fixed`] when any build's is not.
fn value(printed: &str, whole: bool) -> String {
    if whole {
        return printed.to_owned();
    }
    let (int, frac) = printed.split_once('.').unwrap_or((printed, ""));
    let coefficient: String = format!("{int}{frac}");
    let coefficient = coefficient.trim_start_matches('0');
    let coefficient = if coefficient.is_empty() || coefficient == "-" {
        "0"
    } else {
        coefficient
    };
    format!("sts2_core::Fixed::new({coefficient}, {})", frac.len())
}

/// Write `vars.rs` from every build's dumps.
pub fn generate(src: &Path, builds: &[String]) -> Result<PathBuf, DumpError> {
    let mut out = String::from(
        "//! Generated by `cargo xtask codegen`. DO NOT EDIT.\n//!\n\
         //! The numbers every build's models print, as consts each build's enum\n\
         //! implements: `<MODEL>_<VAR>`. A rule shared between builds reads its\n\
         //! numbers through these.\n",
    );
    writeln!(out, "//! Builds: {}.\n", builds.join(", ")).unwrap();

    for kind in KINDS {
        let mut per_build = Vec::new();
        for build in builds {
            let dump = error::read(&src.join(build).join("dumps").join(kind.dump))
                .map_err(DumpError::from)?;
            per_build.push((build, numbers(&dump)));
        }
        // The numbers every build has, in model and name order.
        let shared: BTreeSet<&(String, String)> = per_build
            .iter()
            .map(|(_, numbers)| numbers.keys().collect::<BTreeSet<_>>())
            .reduce(|a, b| a.intersection(&b).copied().collect())
            .unwrap_or_default();
        let whole: BTreeMap<&(String, String), bool> = shared
            .iter()
            .map(|&key| {
                let whole = per_build
                    .iter()
                    .all(|(_, numbers)| !numbers[key].contains('.'));
                (key, whole)
            })
            .collect();
        let ty = |key: &(String, String)| match whole[key] {
            true => "i32",
            false => "sts2_core::Fixed",
        };
        let name =
            |(model, var): &(String, String)| format!("{model}_{}", super::ids::const_name(var));

        writeln!(
            out,
            "/// The numbers each `{}` prints, by model and name.\npub trait {}: 'static {{",
            kind.path.rsplit("::").next().unwrap_or(kind.path),
            kind.trait_name
        )
        .unwrap();
        for key in &shared {
            writeln!(out, "    const {}: {};", name(key), ty(key)).unwrap();
        }
        writeln!(out, "}}\n").unwrap();
        for (build, numbers) in &per_build {
            writeln!(
                out,
                "impl {} for crate::{build}::{} {{",
                kind.trait_name, kind.path
            )
            .unwrap();
            for key in &shared {
                writeln!(
                    out,
                    "    const {}: {} = {};",
                    name(key),
                    ty(key),
                    value(&numbers[*key], whole[*key])
                )
                .unwrap();
            }
            writeln!(out, "}}\n").unwrap();
        }
    }
    let path = src.join("vars.rs");
    error::write(&path, &out).map_err(DumpError::from)?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::value;

    #[test]
    fn a_number_is_whole_or_fixed() {
        assert_eq!(value("5", true), "5");
        assert_eq!(value("0.5", false), "sts2_core::Fixed::new(5, 1)");
        assert_eq!(value("12", false), "sts2_core::Fixed::new(12, 0)");
        assert_eq!(value("1.25", false), "sts2_core::Fixed::new(125, 2)");
    }
}
