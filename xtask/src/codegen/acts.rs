//! Every act: how long it is, and which bosses it reveals in what order.
//! The smallest domain, and the one the others were already pointing at. Monsters, encounters and events each say which act they belong to, and until now nothing said what an act is. Therefore `Act` was generated by the *monsters* domain, from the act ids that happened to appear in its dump. It lives here now, and those three import it.
//! # `index` is not a position
//! `OVERGROWTH` and `UNDERDOCKS` are both index 0. They are the two alternative first acts, and `is_default` is what tells them apart. Therefore a run's shape is 0 then 1 then 2 with a branch at the start, not a straight sequence. Anything treating the index as a unique key is wrong about the first act.
//! It is also signed: the deprecated act is -1.
//! # What is not here
//! `AllEvents`, `AllAncients` and `GenerateAllEncounters` are the same relations the event and encounter dumps already write from the other side. Printing them here as well is two sources for one fact, and the tests cross-check the two rather than the table trusting itself.
//! `GetMapPointTypes` takes an `Rng` and rolls the map's composition, so it is the map generator and gets ported by hand.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use super::{Build, DERIVES, Dump, banner, camel, repr};

pub fn generate(root: &Path) -> Result<Build, String> {
    let dump = Dump::read("acts.txt")?;
    let build = dump.build.clone();

    let acts: Vec<&Vec<String>> = dump.of("act").collect();
    if acts.is_empty() {
        return Err("the dump declares no acts".into());
    }
    for row in &acts {
        if row.len() != 6 {
            return Err(format!("{}: {} columns, not 5", row[1], row.len() - 1));
        }
    }

    // The bosses an act reveals, in order. Kept as a list rather than a set,
    // because the order is which boss a first run ends against.
    let mut bosses: Vec<(String, Vec<String>)> = Vec::new();
    for row in dump.of("boss") {
        let order: usize = row[2]
            .parse()
            .map_err(|e| format!("{}: boss order {}: {e}", row[1], row[2]))?;

        let entry = match bosses.iter_mut().find(|(id, _)| *id == row[1]) {
            Some(entry) => entry,
            None => {
                bosses.push((row[1].clone(), Vec::new()));
                bosses.last_mut().expect("just pushed")
            }
        };

        if entry.1.len() != order {
            return Err(format!(
                "{}: boss {order} arrived out of order, after {}",
                row[1],
                entry.1.len()
            ));
        }
        entry.1.push(row[3].clone());
    }

    let widest = bosses.iter().map(|(_, b)| b.len()).max().unwrap_or(0);
    if widest > BOSS_CAP {
        return Err(format!(
            "an act reveals {widest} bosses, past the {BOSS_CAP} a Bosses can hold"
        ));
    }

    let mut out = banner("Every act's shape and its bosses.", "acts.txt", &build);
    writeln!(out, "\nuse super::encounters::Encounter;").unwrap();
    writeln!(out, "use crate::Few;").unwrap();
    writeln!(out, "use serde::{{Deserialize, Serialize}};\n").unwrap();

    emit_shape(&mut out);
    emit_acts(&mut out, &acts, &bosses)?;

    let path = root.join("acts.rs");
    fs::write(&path, &out).map_err(|e| format!("writing {}: {e}", path.display()))?;

    println!(
        "  acts: {} ({} a run can visit)",
        acts.len(),
        acts.iter().filter(|r| r[2] != "-1").count()
    );

    Ok(build)
}

/// The most bosses an act reveals.
///
/// Three apiece in this build. A cap rather than a guess: generation fails rather than truncating if one ever grows. It is what lets the list be inline instead of a pointer.
const BOSS_CAP: usize = 3;

fn emit_shape(out: &mut String) {
    writeln!(
        out,
        "/// The bosses an act reveals, in discovery order.\n\
         pub type Bosses = Few<Encounter, {BOSS_CAP}>;\n\
         \n\
         /// What is true of an act with no run in progress.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub struct ActData {{\n\
         \x20   /// Where in a run it falls — and not a unique key.\n\
         \x20   ///\n\
         \x20   /// `OVERGROWTH` and `UNDERDOCKS` are both 0: they are the two\n\
         \x20   /// alternative first acts, and `is_default` is what separates\n\
         \x20   /// them. Signed, because the deprecated act is -1.\n\
         \x20   pub index: i8,\n\
         \x20   /// Whether a run starts here when nothing else chose.\n\
         \x20   pub is_default: bool,\n\
         \x20   /// How many rooms the map is before anything modifies it. They\n\
         \x20   /// shrink across a run: 15, 15, 14, 13.\n\
         \x20   pub rooms: u8,\n\
         \x20   /// How many of the act's first fights come from the weak pool.\n\
         \x20   pub weak_encounters: u8,\n\
         \x20   /// The bosses it reveals, in the order a player meets them\n\
         \x20   /// across runs. Order is the rule: it decides which boss a first\n\
         \x20   /// run ends against.\n\
         \x20   pub bosses: Bosses,\n\
         }}\n"
    )
    .unwrap();
}

fn emit_acts(
    out: &mut String,
    acts: &[&Vec<String>],
    bosses: &[(String, Vec<String>)],
) -> Result<(), String> {
    writeln!(
        out,
        "/// Every act in the build, in the order a run visits them.\n\
         ///\n\
         /// Five, not the four `ModelDb.Acts` lists: the deprecated one is\n\
         /// reflected in like every other domain's placeholders, and its index\n\
         /// of -1 is what tells it apart.\n\
         ///\n\
         /// The id is the serde rename, and the only place it is spelled."
    )
    .unwrap();
    writeln!(out, "{DERIVES}").unwrap();
    writeln!(out, "#[repr({})]", repr(acts.len())?).unwrap();
    writeln!(out, "pub enum Act {{").unwrap();
    for row in acts {
        writeln!(out, "    #[serde(rename = \"{}\")]", row[1]).unwrap();
        writeln!(out, "    {},", camel(&row[1])).unwrap();
    }
    writeln!(out, "}}\n").unwrap();

    writeln!(out, "impl Act {{").unwrap();
    writeln!(
        out,
        "    /// Every act, so callers can sweep the table without a way to\n\
         \x20   /// enumerate an enum."
    )
    .unwrap();
    writeln!(out, "    pub const ALL: [Act; {}] = [", acts.len()).unwrap();
    for row in acts {
        writeln!(out, "        Act::{},", camel(&row[1])).unwrap();
    }
    writeln!(out, "    ];\n").unwrap();

    writeln!(out, "    /// The act's shape and its bosses.").unwrap();
    writeln!(out, "    pub const fn data(self) -> ActData {{").unwrap();
    writeln!(out, "        match self {{").unwrap();
    for row in acts {
        let id = &row[1];
        let number = |what: &str, v: &str| {
            v.parse::<u8>()
                .map_err(|e| format!("{id}: {what} {v}: {e}"))
        };
        let index = row[2]
            .parse::<i8>()
            .map_err(|e| format!("{id}: index {}: {e}", row[2]))?;

        let list = bosses
            .iter()
            .find(|(act, _)| act == id)
            .map(|(_, b)| {
                b.iter()
                    .map(|e| format!("Encounter::{}", camel(e)))
                    .collect::<Vec<_>>()
                    .join(", ")
            })
            .unwrap_or_default();

        writeln!(out, "            Self::{} => ActData {{", camel(id)).unwrap();
        writeln!(out, "                index: {index},").unwrap();
        writeln!(out, "                is_default: {},", row[3] == "1").unwrap();
        writeln!(out, "                rooms: {},", number("rooms", &row[4])?).unwrap();
        writeln!(
            out,
            "                weak_encounters: {},",
            number("weak encounters", &row[5])?
        )
        .unwrap();
        writeln!(out, "                bosses: Bosses::new(&[{list}]),").unwrap();
        writeln!(out, "            }},").unwrap();
    }
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();

    Ok(())
}
