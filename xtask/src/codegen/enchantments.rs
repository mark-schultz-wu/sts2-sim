//! Every enchantment: what it can go on, and the flags around it.
//!
//! An enchantment is a modifier stuck to a card. What it *does* is
//! `EnchantDamageAdditive` and friends, which are code.
//!
//! # `enchants` is the effective set, not the probe
//!
//! The dump asks `CanEnchantCardType` about every card type, and that method
//! answers for more types than an enchantment can actually reach: seventeen of
//! the twenty-four say yes to `Curse`, `Status`, `Quest` and even the game's
//! `CardType.None`, because the base implementation returns true for anything
//! and the real filter is elsewhere.
//!
//! `EnchantmentModel.CanEnchant` refuses card types 4, 5 and 6 — Status, Curse
//! and Quest — for every enchantment before it ever asks
//! `CanEnchantCardType`. So the set generated here is the probe intersected
//! with the three types that survive that, which is what an enchantment can be
//! put on. The raw answers stay in the dump, so the intersection is visible
//! rather than assumed.
//!
//! `CardType.None` is not generated by the cards domain at all, so it could not
//! be spelled here even if it meant something.
//!
//! # `IsStackable` is not a column
//!
//! No enchantment overrides it, so all twenty-four take the `false` default. A
//! column would be the same value twenty-four times, which says nothing about
//! any of them — the same reason `StartingPotions` is not a character column.
//!
//! # One file
//!
//! Twenty-four rows and no grouping to split on: enchantments have no pool, no
//! rarity and no act.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use super::{DERIVES, Dump, banner, camel, repr};

/// The card types an enchantment can actually be put on.
///
/// The three `EnchantmentModel.CanEnchant` does not refuse outright. Anything
/// else the probe reports is unreachable — see the module docs.
const ENCHANTABLE: [&str; 3] = ["Attack", "Skill", "Power"];

/// The yes-or-no columns, in the order they become bits.
const FLAGS: [(&str, usize, &str); 4] = [
    ("ExtraCardText", 2, "Adds a line to the card it is on."),
    ("ShowsAmount", 3, "Displays a number beside itself."),
    (
        "StartsAtBottomOfDrawPile",
        4,
        "The card it is on begins the fight at the bottom of the draw\n\
         pile. One enchantment does this.",
    ),
    (
        "RefusesSomeCards",
        6,
        "Has a rule beyond the card's type: `CanEnchant` takes a whole\n\
         `CardModel` and five enchantments override it, so one can\n\
         refuse a card whose type it otherwise accepts. What the rule\n\
         *is* is code; that there is one is what an offer needs.",
    ),
];

pub fn generate(root: &Path) -> Result<String, String> {
    let dump = Dump::read("enchantments.txt")?;
    let hash = dump.hash.clone();

    let enchantments: Vec<&Vec<String>> = dump.of("enchantment").collect();
    if enchantments.is_empty() {
        return Err("the dump declares no enchantments".into());
    }
    for row in &enchantments {
        if row.len() != 7 {
            return Err(format!("{}: {} columns, not 6", row[1], row.len() - 1));
        }
        // The column exists in the dump and is not generated, so a build that
        // starts using it fails here rather than losing it silently.
        if row[5] != "0" {
            return Err(format!(
                "{} is stackable, which no enchantment was when the column was dropped",
                row[1]
            ));
        }
    }

    let mut types: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for row in dump.of("enchants") {
        if ENCHANTABLE.contains(&row[2].as_str()) {
            types
                .entry(row[1].clone())
                .or_default()
                .push(row[2].clone());
        }
    }

    let mut out = banner(
        "Every enchantment's card types and flags.",
        "enchantments.txt",
        &hash,
    );
    writeln!(out, "\nuse super::cards::CardType;").unwrap();
    writeln!(out, "use serde::{{Deserialize, Serialize}};\n").unwrap();

    emit_set(&mut out);
    emit_flags(&mut out);
    emit_shape(&mut out);
    emit_enchantments(&mut out, &enchantments, &types)?;

    let path = root.join("enchantments.rs");
    fs::write(&path, &out).map_err(|e| format!("writing {}: {e}", path.display()))?;

    let restricted = enchantments
        .iter()
        .filter(|r| types.get(&r[1]).is_none_or(|t| t.len() < ENCHANTABLE.len()))
        .count();
    println!(
        "  enchantments: {} ({restricted} restrict their card types)",
        enchantments.len()
    );

    Ok(hash)
}

/// A set over the cards domain's `CardType`.
///
/// Declared here rather than there because nothing else needs one. If a second
/// domain ever does, this is the one to move.
fn emit_set(out: &mut String) {
    writeln!(
        out,
        "/// The card types an enchantment can be put on.\n\
         ///\n\
         /// Only ever a subset of `Attack`, `Skill` and `Power`:\n\
         /// `EnchantmentModel.CanEnchant` refuses Status, Curse and Quest for\n\
         /// every enchantment before asking it anything, so the other three are\n\
         /// unreachable however `CanEnchantCardType` answers about them.\n\
         #[derive(Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub struct CardTypeSet(u8);\n\
         \n\
         impl CardTypeSet {{\n\
         \x20   /// The reachable types, in the game's declaration order.\n\
         \x20   const MEMBERS: [CardType; {n}] = [{members}];\n\
         \n\
         \x20   pub const fn new(types: &[CardType]) -> Self {{\n\
         \x20       let mut bits = 0u8;\n\
         \x20       let mut i = 0;\n\
         \x20       while i < types.len() {{\n\
         \x20           bits |= 1u8 << types[i] as u8;\n\
         \x20           i += 1;\n\
         \x20       }}\n\
         \x20       Self(bits)\n\
         \x20   }}\n\
         \n\
         \x20   pub const fn contains(self, ty: CardType) -> bool {{\n\
         \x20       self.0 & (1u8 << ty as u8) != 0\n\
         \x20   }}\n\
         \n\
         \x20   pub const fn is_empty(self) -> bool {{\n\
         \x20       self.0 == 0\n\
         \x20   }}\n\
         \n\
         \x20   pub fn iter(self) -> impl Iterator<Item = CardType> {{\n\
         \x20       Self::MEMBERS.into_iter().filter(move |&t| self.contains(t))\n\
         \x20   }}\n\
         }}\n\
         \n\
         impl std::fmt::Debug for CardTypeSet {{\n\
         \x20   fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{\n\
         \x20       f.debug_set().entries(self.iter()).finish()\n\
         \x20   }}\n\
         }}\n",
        n = ENCHANTABLE.len(),
        members = ENCHANTABLE
            .iter()
            .map(|t| format!("CardType::{t}"))
            .collect::<Vec<_>>()
            .join(", "),
    )
    .unwrap();
}

fn emit_flags(out: &mut String) {
    writeln!(
        out,
        "/// A yes-or-no fact about an enchantment.\n\
         ///\n\
         /// Four separate `EnchantmentModel` members rather than a game enum,\n\
         /// so the numbering is the order the dump writes the columns in.\n\
         {DERIVES}\n\
         #[repr(u8)]\n\
         pub enum EnchantmentFlag {{"
    )
    .unwrap();
    for (bit, (name, _, doc)) in FLAGS.iter().enumerate() {
        for line in doc.lines() {
            writeln!(out, "    /// {}", line.trim()).unwrap();
        }
        writeln!(out, "    {name} = {bit},").unwrap();
    }
    writeln!(out, "}}\n").unwrap();

    writeln!(
        out,
        "/// The flags an enchantment has.\n\
         ///\n\
         /// One word and a `contains`: none of these is ever computed, because\n\
         /// all four are read off the model with no run underneath it.\n\
         #[derive(Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub struct EnchantmentFlags(u8);\n\
         \n\
         impl EnchantmentFlags {{\n\
         \x20   const MEMBERS: [EnchantmentFlag; {n}] = [{members}];\n\
         \n\
         \x20   pub const fn new(flags: &[EnchantmentFlag]) -> Self {{\n\
         \x20       let mut bits = 0u8;\n\
         \x20       let mut i = 0;\n\
         \x20       while i < flags.len() {{\n\
         \x20           bits |= 1u8 << flags[i] as u8;\n\
         \x20           i += 1;\n\
         \x20       }}\n\
         \x20       Self(bits)\n\
         \x20   }}\n\
         \n\
         \x20   pub const fn contains(self, flag: EnchantmentFlag) -> bool {{\n\
         \x20       self.0 & (1u8 << flag as u8) != 0\n\
         \x20   }}\n\
         \n\
         \x20   pub fn iter(self) -> impl Iterator<Item = EnchantmentFlag> {{\n\
         \x20       Self::MEMBERS.into_iter().filter(move |&f| self.contains(f))\n\
         \x20   }}\n\
         }}\n\
         \n\
         impl std::fmt::Debug for EnchantmentFlags {{\n\
         \x20   fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{\n\
         \x20       f.debug_set().entries(self.iter()).finish()\n\
         \x20   }}\n\
         }}\n",
        n = FLAGS.len(),
        members = FLAGS
            .iter()
            .map(|(name, ..)| format!("EnchantmentFlag::{name}"))
            .collect::<Vec<_>>()
            .join(", "),
    )
    .unwrap();
}

fn emit_shape(out: &mut String) {
    writeln!(
        out,
        "/// What is true of an enchantment with no run in progress.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub struct EnchantmentData {{\n\
         \x20   /// The card types it can be put on. Never empty, and all three\n\
         \x20   /// for seventeen of the twenty-four.\n\
         \x20   pub enchants: CardTypeSet,\n\
         \x20   pub flags: EnchantmentFlags,\n\
         }}\n"
    )
    .unwrap();
}

fn emit_enchantments(
    out: &mut String,
    enchantments: &[&Vec<String>],
    types: &BTreeMap<String, Vec<String>>,
) -> Result<(), String> {
    writeln!(
        out,
        "/// Every enchantment in the build.\n\
         ///\n\
         /// One file: there is no pool, rarity or act to group them by.\n\
         ///\n\
         /// The id is the serde rename, and the only place it is spelled."
    )
    .unwrap();
    writeln!(out, "{DERIVES}").unwrap();
    writeln!(out, "#[repr({})]", repr(enchantments.len())?).unwrap();
    writeln!(out, "pub enum Enchantment {{").unwrap();
    for row in enchantments {
        writeln!(out, "    #[serde(rename = \"{}\")]", row[1]).unwrap();
        writeln!(out, "    {},", camel(&row[1])).unwrap();
    }
    writeln!(out, "}}\n").unwrap();

    writeln!(out, "impl Enchantment {{").unwrap();
    writeln!(
        out,
        "    /// Every enchantment, so callers can sweep the table without a way\n\
         \x20   /// to enumerate an enum."
    )
    .unwrap();
    writeln!(
        out,
        "    pub const ALL: [Enchantment; {}] = [",
        enchantments.len()
    )
    .unwrap();
    for row in enchantments {
        writeln!(out, "        Enchantment::{},", camel(&row[1])).unwrap();
    }
    writeln!(out, "    ];\n").unwrap();

    writeln!(out, "    /// The card types it goes on, and the flags.").unwrap();
    writeln!(out, "    pub const fn data(self) -> EnchantmentData {{").unwrap();
    writeln!(out, "        match self {{").unwrap();
    for row in enchantments {
        let empty = Vec::new();
        let allowed = types.get(&row[1]).unwrap_or(&empty);
        if allowed.is_empty() {
            return Err(format!("{} can be put on nothing at all", row[1]));
        }

        let set = allowed
            .iter()
            .map(|t| format!("CardType::{t}"))
            .collect::<Vec<_>>()
            .join(", ");
        let flags = FLAGS
            .iter()
            .filter(|(_, column, _)| row[*column] == "1")
            .map(|(name, ..)| format!("EnchantmentFlag::{name}"))
            .collect::<Vec<_>>()
            .join(", ");

        writeln!(
            out,
            "            Self::{} => EnchantmentData {{",
            camel(&row[1])
        )
        .unwrap();
        writeln!(out, "                enchants: CardTypeSet::new(&[{set}]),").unwrap();
        writeln!(
            out,
            "                flags: EnchantmentFlags::new(&[{flags}]),"
        )
        .unwrap();
        writeln!(out, "            }},").unwrap();
    }
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();

    Ok(())
}
